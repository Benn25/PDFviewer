# Builds the portable app and zips it:
#
#   dist\PDF Viewer\
#     PDF Viewer.exe            the app: a WebView2 window around app\index.html
#     Add to Windows.cmd        Start Menu entry, "Open with" and right-click entry for PDFs
#     Remove from Windows.cmd
#     Read me first.txt         and the same in Japanese
#     app\                      the page, pdf.js, the WebView2 libraries, icon, setup.ps1
#   dist\PDF Viewer <version>.zip   to hand to others
#
#   npm run build     (after `npm install`, which fetches pdf.js)
#   npm run deploy    the same, then copies the app over your own installed copy
#
# The version comes from package.json: bump it there for each release.

param([string]$InstallTo)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$dist = Join-Path $root 'dist'
$out = Join-Path $dist 'PDF Viewer'
$app = Join-Path $out 'app'
$pdfjs = Join-Path $root 'node_modules\pdfjs-dist'
$sdkVersion = '1.0.4314.35'
$version = (Get-Content -Raw (Join-Path $root 'package.json') | ConvertFrom-Json).version

if (-not (Test-Path $pdfjs)) { throw 'node_modules\pdfjs-dist is missing: run "npm install" first.' }

# The WebView2 SDK (two .NET libraries and the native loader), from NuGet, once.
$sdk = Join-Path $PSScriptRoot "webview2\$sdkVersion"
if (-not (Test-Path (Join-Path $sdk 'lib'))) {
  New-Item -ItemType Directory -Force $sdk | Out-Null
  $pkg = Join-Path $sdk 'package.zip'
  Write-Host "Downloading the WebView2 SDK $sdkVersion from NuGet..."
  Invoke-WebRequest -UseBasicParsing -OutFile $pkg `
    "https://api.nuget.org/v3-flatcontainer/microsoft.web.webview2/$sdkVersion/microsoft.web.webview2.$sdkVersion.nupkg"
  Expand-Archive -LiteralPath $pkg -DestinationPath $sdk -Force
  Remove-Item -LiteralPath $pkg
}
$core = Join-Path $sdk 'lib\net462\Microsoft.Web.WebView2.Core.dll'
$winforms = Join-Path $sdk 'lib\net462\Microsoft.Web.WebView2.WinForms.dll'
$loader = Join-Path $sdk 'runtimes\win-x64\native\WebView2Loader.dll'

$icon = Join-Path $PSScriptRoot 'icon.ico'
if (-not (Test-Path $icon)) { & (Join-Path $PSScriptRoot 'make-icon.ps1') | Out-Null }

if (Test-Path $dist) { Remove-Item -LiteralPath $dist -Recurse -Force }
New-Item -ItemType Directory -Force $app | Out-Null

# The version, stamped into the exe (file properties, and the menu shows it).
$obj = Join-Path $PSScriptRoot 'obj'
New-Item -ItemType Directory -Force $obj | Out-Null
$versionFile = Join-Path $obj 'Version.cs'
Set-Content -LiteralPath $versionFile -Encoding UTF8 -Value @(
  '// Generated by build.ps1 from package.json.',
  "[assembly: System.Reflection.AssemblyVersion(""$version.0"")]",
  "[assembly: System.Reflection.AssemblyFileVersion(""$version.0"")]",
  "[assembly: System.Reflection.AssemblyInformationalVersion(""$version"")]"
)

# The exe, with the .NET Framework compiler every Windows 10/11 has.
$csc = Join-Path $env:SystemRoot 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
& $csc /nologo /target:winexe /platform:x64 /optimize+ `
  "/win32icon:$icon" "/win32manifest:$root\host\app.manifest" `
  /reference:System.Windows.Forms.dll /reference:System.Drawing.dll "/reference:$core" "/reference:$winforms" `
  "/out:$out\PDF Viewer.exe" "$root\host\PDFViewer.cs" $versionFile
if ($LASTEXITCODE -ne 0) { throw 'Compiling host\PDFViewer.cs failed.' }

Copy-Item -LiteralPath "$root\windows\Add to Windows.cmd", "$root\windows\Remove from Windows.cmd" -Destination $out
Copy-Item -LiteralPath "$root\index.html", "$root\windows\setup.ps1", $icon, $core, $winforms, $loader -Destination $app
Copy-Item -LiteralPath (Join-Path $sdk 'LICENSE.txt') -Destination (Join-Path $app 'WebView2-LICENSE.txt')

# Read-me files: Windows line ends, and a BOM so Notepad reads the Japanese one right.
$utf8Bom = New-Object System.Text.UTF8Encoding $true
foreach ($txt in Get-ChildItem -LiteralPath "$root\windows" -Filter '*.txt') {
  $text = [System.IO.File]::ReadAllText($txt.FullName, [System.Text.Encoding]::UTF8) -replace "`r?`n", "`r`n"
  [System.IO.File]::WriteAllText((Join-Path $out $txt.Name), $text, $utf8Bom)
}

# pdf.js: only what the page loads.
New-Item -ItemType Directory -Force "$app\pdfjs\build" | Out-Null
Copy-Item -LiteralPath "$pdfjs\build\pdf.min.mjs", "$pdfjs\build\pdf.worker.min.mjs" -Destination "$app\pdfjs\build"
Copy-Item -LiteralPath "$pdfjs\cmaps", "$pdfjs\standard_fonts" -Destination "$app\pdfjs" -Recurse
Copy-Item -LiteralPath "$pdfjs\LICENSE" -Destination "$app\pdfjs\LICENSE"

$zip = Join-Path $dist "PDF Viewer $version.zip"
Compress-Archive -Path $out -DestinationPath $zip

$folderMB = (Get-ChildItem $out -Recurse -File | Measure-Object Length -Sum).Sum / 1MB
Write-Host ('Built PDF Viewer {0}: {1} ({2:N1} MB), zipped to {3} ({4:N1} MB)' -f $version, $out, $folderMB, $zip, ((Get-Item $zip).Length / 1MB))

# Update an installed copy in place. Its registration points at the same paths,
# so there is nothing to re-run unless setup.ps1 itself changed.
if ($InstallTo) {
  $target = (Resolve-Path -LiteralPath $InstallTo).Path.TrimEnd('\')
  $running = Get-Process -Name 'PDF Viewer' -ErrorAction SilentlyContinue |
    Where-Object { $_.Path -and $_.Path.StartsWith($target + '\', [StringComparison]::OrdinalIgnoreCase) }
  if ($running) { throw "PDF Viewer is open from $target - close it, then run this again." }
  Copy-Item -Path "$out\*" -Destination $target -Recurse -Force
  Write-Host "Updated $target to $version"
}
